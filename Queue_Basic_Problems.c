/*
========================================
기초 개념 정리
========================================

큐 (Queue)란?
- FIFO (First In First Out): 먼저 들어온 것이 먼저 나간다
- 예: 은행 대기열, 프린터 대기열

큐의 기본 연산:
1. enqueue: 뒤에 추가
2. dequeue: 앞에서 제거
3. peek/front: 앞의 원소 확인 (제거 안함)
4. isEmpty: 비어있는지 확인
5. getSize: 원소의 개수

배열로 큐 구현할 때:
- front: 첫 번째 원소의 위치
- rear: 마지막 원소의 위치
- 원소 개수 = rear - front + 1

예시:
초기: front=0, rear=-1, 원소 없음
enqueue(10): front=0, rear=0, arr[0]=10
enqueue(20): front=0, rear=1, arr[1]=20
dequeue(): front=1, rear=1, 10 반환
========================================
*/
