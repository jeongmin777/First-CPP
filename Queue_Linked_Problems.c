/*
========================================
배열 큐 vs 연결 큐 비교
========================================

배열 큐 (Linear Queue):
- 장점: 구현이 간단, 빠른 접근
- 단점: 크기가 고정됨, 메모리 낭비 가능
        (dequeue 후 front 앞의 공간 재사용 불가)

연결 큐 (Linked Queue):
- 장점: 동적으로 크기 변경, 메모리 효율적
- 단점: 구현이 복잡, 포인터 관리 필요, 메모리 해제 필수

연결 큐의 특징:
1. 각 노드는 독립적으로 메모리 할당됨
2. enqueue 시 새 노드를 malloc으로 생성
3. dequeue 시 노드를 free로 해제
4. front와 rear로 큐의 범위 관리
5. 크기 제한이 없음 (메모리 크기만큼 가능)

예시:
빈 큐: front=NULL, rear=NULL

enqueue(10):
  front -> [10|NULL]
  rear  -> [10|NULL]

enqueue(20):
  front -> [10|next] -> [20|NULL]
  rear              -> [20|NULL]

dequeue():
  제거할 노드: [10|next]
  front -> [20|NULL]
  rear  -> [20|NULL]

========================================
*/
